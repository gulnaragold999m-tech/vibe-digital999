using UnityEngine;

// Карта уровня. Одна строка файла — одна строка мира, сверху вниз, как на
// экране. Править её можно обычным текстовым редактором: игра читает карту
// при запуске, ничего пересобирать не нужно.
//
// Что означают знаки:
//
//   .  пусто            #  земля (трава сверху рисуется сама)
//   X  каменный блок    =  кирпич (большой герой его разбивает)
//   ?  блок с монетой   !  блок с грибом
//   o  монета           g  враг-ходун
//   p  труба (где верх и где левая половина — считается само)
//   P  старт героя      F  финишный шест
//   c  облако           b  куст            h  холм   (только для вида)
//
// Правило одно: все строки одной длины. При запуске это проверяется, и кривая
// строка сразу видна в консоли Unity — искать опечатку глазами не придётся.
public static class Uroven
{
    public static readonly string[] Karta =
    {
        "....................................................................................................................................................................................................",
        "....................................................................................................................................................................................................",
        "....................................................................................................................................................................................................",
        "......................c.....................................c..................................c............................................c...................................c...................",
        "........c...............................c.....................................c.......................................c..........................ooo..............c.................................",
        ".....................ooo..............................................==!===......................................................o..o..............................ooo..........X..................",
        "..................................................................................................................................=?!=..........................................XX..................",
        "...............................................................................................................................................................................XXX..................",
        "..................................ooo..................................o.o.o....................oo.................o.o..........................==?==.........................XXXX..................",
        "................?...=?=!=.............................................==?=?=...................X.X................==?==...........................................=?=?=......XXXXX..................",
        "..................................................pp............pp............................XX.XX...........................pp............................................XXXXXX..................",
        "........................................pp........pp............pp...........................XXX.XXX..........................pp............................pp.............XXXXXXX..................",
        "...Ph.....b...............g...h.........pp...gg.b.pp...h........pp..g.......b.g.g.h.........XXXX.XXXX...g...............g.g...pp..h.........ggg...b.........pph.g.........XXXXXXXX..h...F...........",
        "##################################...#####################...#########################...###################.....#####################...#############...###########################################",
        "##################################...#####################...#########################...###################.....#####################...#############...###########################################"
    };

    // Проверка при запуске: строки одной длины и старт героя на карте есть.
    // Дешевле поймать это здесь, чем ловить потом «герой падает в пустоту».
    public static bool Proverit()
    {
        bool horosho = true;
        int shirina = Karta[0].Length;
        bool estStart = false;
        for (int i = 0; i < Karta.Length; i++)
        {
            if (Karta[i].Length != shirina)
            {
                Debug.LogError("Уровень: строка " + i + " длиной " + Karta[i].Length +
                               ", а первая строка — " + shirina + ". Дописать или укоротить.");
                horosho = false;
            }
            if (Karta[i].IndexOf('P') >= 0) estStart = true;
        }
        if (!estStart)
        {
            Debug.LogError("Уровень: на карте нет знака P — героя негде поставить.");
            horosho = false;
        }
        return horosho;
    }
}
