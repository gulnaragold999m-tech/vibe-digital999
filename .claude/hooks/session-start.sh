#!/bin/bash
# Памятка проекта в начало каждой беседы.
#
# ЗАЧЕМ. Правила лежат в CLAUDE.md, но чат читает тот CLAUDE.md, который
# оказался в его ветке, — а ветки расходятся. 11.08.2026 из-за этого один
# чат собрал второй генератор страниц поверх существующего. Хук печатает
# памятку независимо от ветки: пропустить её нельзя.
set -euo pipefail
cd "${CLAUDE_PROJECT_DIR:-$(pwd)}" 2>/dev/null || exit 0

# Запоминаем, с чего беседа началась: по этому снимку Stop-хук поймёт,
# менялось ли что-нибудь и дописан ли журнал.
git rev-parse HEAD > .git/claude-session-start-sha 2>/dev/null || true
rm -f .git/claude-journal-reminded 2>/dev/null || true

BRANCH=$(git branch --show-current 2>/dev/null || echo 'неизвестна')

# Свежесть трёх файлов памяти хук считает САМ.
#
# ЗАЧЕМ. Раньше в памятке стояла просьба «проверь, не обновляли ли правила
# в другой ветке». Просьбу можно не выполнить, и её не выполняли: 12.08.2026
# соседний чат читал журнал своей ветки, а он кончался 10 августа, и доложил
# владелице, что работа за 11-е не записана. Записана — в другой ветке.
# Просьба заменена на факт: хук сравнивает файл в этой ветке со всеми
# ветками origin и печатает, где лежит свежий.
timeout 20 git fetch --quiet origin >/dev/null 2>&1 || true

svezhee() {  # $1 — имя файла; печатает строку предупреждения или ничего
  local file="$1" ref ts best_ref='' best_ts=0
  [ -f "$file" ] || return 0
  while read -r ref; do
    ts=$(git log -1 --format='%ct' "$ref" -- "$file" 2>/dev/null || true)
    [ -z "$ts" ] && continue
    if [ "$ts" -gt "$best_ts" ]; then best_ts="$ts"; best_ref="$ref"; fi
  done < <(git for-each-ref --format='%(refname:short)' refs/remotes/origin 2>/dev/null | grep -v 'HEAD$' || true)
  [ -z "$best_ref" ] && return 0
  # Сравниваем по содержимому, а не по дате: одинаковый файл в двух ветках
  # не повод для тревоги, даже если коммиты разного возраста.
  git show "$best_ref:$file" 2>/dev/null | cmp -s - "$file" && return 0
  local kogda
  kogda=$(git log -1 --date=format:'%d.%m %H:%M' --format='%cd' "$best_ref" -- "$file" 2>/dev/null || echo '?')
  printf '   %s — свежее в %s (%s). Прочитать: git show %s:%s\n' \
    "$file" "$best_ref" "$kogda" "$best_ref" "$file"
}

USTARELO=$( { svezhee CLAUDE.md; svezhee STATUS.md; svezhee TASKS.md; } 2>/dev/null || true)
if [ -n "$USTARELO" ]; then
  PUNKT2=$(printf 'В ТВОЕЙ ВЕТКЕ УСТАРЕВШАЯ ПАМЯТЬ. Свежее лежит в другой ветке:\n\n%s\n   Работай по свежей версии, свою последней не считай.' "$USTARELO")
else
  PUNKT2='Все три файла памяти в твоей ветке — самые свежие из всех веток.
   Проверил хук, перепроверять не нужно.'
fi

# Живую ветку не вписываем сюда числом: она меняется. Берём строкой
# из STATUS.md — обновили там, обновилось и здесь.
# Берём ровно одно предложение — до первой точки. Строка в STATUS.md
# продолжается на следующей, и без обрезки в памятку попадал обрывок
# вроде «…Выкатана» без окончания.
LIVE=$(grep -m1 'На живом сайте сейчас ветка' STATUS.md 2>/dev/null \
  | tr -d '*`' | sed 's/\([^.]*\.\).*/\1/' || true)
[ -z "$LIVE" ] && LIVE='Какая ветка на живом сайте — смотри STATUS.md.'

MEMO=$(cat <<TXT
ПАМЯТКА ПРОЕКТА vibe-digital999 — печатает хук, до первой правки.

1. Прочитай ТРИ файла: CLAUDE.md (правила), STATUS.md (где что лежит,
   карта веток), TASKS.md (журнал по дням, где остановились).
   Не спрашивай владелицу про устройство проекта — всё записано там.

2. ${PUNKT2}

3. ${LIVE}
   main на сайт не выкатывать: там вторая, лишняя система сборки.

4. Выкатка — два шага, fetch строго первым:
   git fetch origin <ветка>
   git push --force amvera origin/<ветка>:master

5. Страницы правятся в src/, не в public/. Собранное в public/ руками
   не чистить: prestart стоит с "|| true", сломанная сборка проходит
   молча, и эти файлы — единственная страховка сайта.

6. Перед словом «готово» допиши TASKS.md по шаблону из CLAUDE.md:
   цель дня, сделано, где остановились, что ждём от Гульнары, что не
   доделано. Незаписанное для следующего чата не существует.

7. НЕ ГОВОРИ ВЛАДЕЛИЦЕ «этого не сделано», прочитав один журнал.
   Пустая строчка в журнале не значит, что работы не было: её могли
   записать в другой ветке, другими словами или не записать вовсе.
   Сначала проверь по истории всех веток и по коду живой ветки:
   git log --all --since='7 days ago' --format='%h %cd %s' -- src public
   Она спрашивает про журнал, чтобы не переделать вчерашнее. Ответ
   «не сделано» без этой проверки стоит ей рабочего дня.

Твоя ветка: ${BRANCH}
TXT
)

python3 - "$MEMO" <<'PY' 2>/dev/null || printf '%s\n' "$MEMO"
import json, sys
print(json.dumps({"hookSpecificOutput": {
    "hookEventName": "SessionStart",
    "additionalContext": sys.argv[1],
}}, ensure_ascii=False))
PY
