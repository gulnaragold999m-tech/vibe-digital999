// ─────────────────── поиск ───────────────────
// Ищем по всему тексту сразу, а не построчно: устойчивые обороты вроде
// «самые низкие цены» часто разрываются переносом строки, и построчный
// поиск их пропускает. Номер строки восстанавливаем по позиции совпадения.
const flat = clean.replace(/[ \t]+/g, ' ');
const lineStarts = [0];
for (let i = 0; i < flat.length; i++) if (flat[i] === '\n') lineStarts.push(i + 1);
const lineOf = pos => { let l = 1; for (let i = 0; i < lineStarts.length; i++) if (pos >= lineStarts[i]) l = i + 1; return l; };
const searchable = flat.replace(/\n/g, ' '); // те же индексы, но переносы не мешают обороту

const hits = [];
const seen = new Set();
for (const g of GROUPS) {
  for (const w of g.words) {
    const re = new RegExp('(^|[^а-яёa-z])(' + w + '[а-яё]*)', 'gi');
    let m;
    while ((m = re.exec(searchable)) !== null) {
      const pos = m.index + m[1].length;
      const key = g.id + ':' + pos;
      if (seen.has(key)) continue;
      seen.add(key);
      hits.push({ group: g.id, groupName: g.name, why: g.why, weight: g.weight,
        word: m[2], line: lineOf(pos),
        context: searchable.slice(Math.max(0, pos - 40), pos + 80).trim() });
    }
  }
}

// ─────────────────── синтаксис ───────────────────
const syntax = [];
const sentences = searchable.replace(/\s+/g, ' ').split(/(?<=[.!?])\s+/).filter(s => s.trim().length > 1);
const longOnes = sentences.filter(s => s.split(/\s+/).length > 22);
if (longOnes.length) syntax.push({
  id: 'long', name: `Длинных предложений: ${longOnes.length}`,
  why: 'Больше 22 слов — читатель теряет нить. Разбей на два.',
  samples: longOnes.slice(0, 3).map(s => s.slice(0, 130) + '…'),
});

// \b в JS работает по латинице, поэтому границу слова задаём явно через (?![а-яё])
const passive = [...searchable.matchAll(/(был[аиео]?|будет|будут|быть)\s+([а-яё]+(?:н|т))(ы|о|а)?(?![а-яё])/gi)].map(m => m[0].trim());
if (passive.length) syntax.push({
  id: 'passive', name: `Пассивный залог: ${passive.length}`,
  why: 'Живой текст строится по формуле «кто-то делает что-то». «Работы были выполнены» → «сдали».',
  samples: [...new Set(passive)].slice(0, 5),
});

const chains = [...searchable.matchAll(/\b[а-яё]+(ия|ии|ов|ения|ования|ности|ства)\s+[а-яё]+(ия|ии|ов|ения|ования|ности|ства)\s+[а-яё]+(ия|ии|ов|ения|ования|ности|ства)/gi)].map(m => m[0]);
if (chains.length) syntax.push({
  id: 'chains', name: `Цепочек родительных падежей: ${chains.length}`,
  why: 'Три существительных подряд читаются тяжело. Переписывай глаголами.',
  samples: [...new Set(chains)].slice(0, 4),
});

const we = (searchable.match(/(^|\s)(мы|нас|нам|наш[аиеу]?[йямх]?)\b/gi) || []).length;
const you = (searchable.match(/(^|\s)(вы|вас|вам|ваш[аиеу]?[йямх]?)\b/gi) || []).length;

// ─────────────────── итог ───────────────────
const words = searchable.split(/\s+/).filter(Boolean).length;
const chars = searchable.replace(/\s+/g, ' ').trim().length;
const penalty = hits.reduce((s, h) => s + h.weight, 0);
const density = words ? penalty / (words / 100) : 0;
const score = Math.max(0, Math.min(10, 10 - density * 1.2));

if (asJson) {
  console.log(JSON.stringify({ chars, words, score: +score.toFixed(1), hits, syntax, weRatio: { we, you } }, null, 2));
  process.exit(0);
}

const byGroup = {};
for (const h of hits) (byGroup[h.groupName] ||= []).push(h);

console.log(`\n📝 Проверка текста${file ? ': ' + file : ''}`);
console.log(`   ${chars} знаков · ${words} слов · оценка ${score.toFixed(1)}/10\n`);

if (!hits.length && !syntax.length) {
  console.log('Стоп-слов и тяжёлых конструкций не нашлось. Прочитай вслух — это ловит то, что скрипт не видит.\n');
} else {
  for (const [name, list] of Object.entries(byGroup).sort((a, b) => b[1].length - a[1].length)) {
    console.log(`▸ ${name} — ${list.length}`);
    if (verbose) console.log(`  ${list[0].why}`);
    const uniq = [...new Set(list.map(h => h.word.toLowerCase()))].slice(0, 12);
    console.log('  ' + uniq.join(', '));
    if (verbose) list.slice(0, 3).forEach(h => console.log(`    стр. ${h.line}: …${h.context}…`));
    console.log('');
  }
  for (const s of syntax) {
    console.log(`▸ ${s.name}`);
    if (verbose) console.log(`  ${s.why}`);
    s.samples.forEach(x => console.log(`    · ${x}`));
    console.log('');
  }
}

if (we > you * 1.5 && we > 5) {
  console.log(`▸ Текст про себя, а не про читателя: «мы» — ${we}, «вы» — ${you}`);
  console.log('  Переверни формулировки: не «мы используем чистый код», а «сайт остаётся вашим».\n');
}

