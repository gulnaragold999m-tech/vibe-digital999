/**
 * check-text.mjs — проверка текста на стоп-слова, канцелярит и тяжёлый синтаксис.
 * Node 18+, без зависимостей.
 *
 *   node check-text.mjs tekst.md
 *   node check-text.mjs tekst.md --verbose     # с пояснением по каждой находке
 *   node check-text.mjs tekst.md --json
 *   cat tekst.md | node check-text.mjs         # из потока
 *
 * Скрипт показывает места, на которые стоит посмотреть. Он не знает контекста:
 * «очень» в цитате клиента звучит живо, в описании услуги — пусто. Решение
 * всегда за автором. Механическое удаление найденного делает текст короче,
 * но не лучше — на месте оценки должен появиться факт.
 */

import { readFileSync } from 'fs';

const argv = process.argv.slice(2);
const verbose = argv.includes('--verbose') || argv.includes('-v');
const asJson = argv.includes('--json');
const file = argv.find(a => !a.startsWith('-'));

let text = '';
if (file) {
  try { text = readFileSync(file, 'utf8'); }
  catch (e) { console.error('Не удалось прочитать файл: ' + e.message); process.exit(1); }
} else if (!process.stdin.isTTY) {
  text = readFileSync(0, 'utf8');
} else {
  console.error('Использование: node check-text.mjs tekst.md [--verbose] [--json]');
  process.exit(1);
}

// Убираем разметку, чтобы не считать её за текст
const clean = text
  .replace(/```[\s\S]*?```/g, ' ')
  .replace(/`[^`]*`/g, ' ')
  .replace(/<[^>]+>/g, ' ')
  .replace(/!?\[([^\]]*)\]\([^)]*\)/g, '$1')
  .replace(/^[#>\-*\s|]+/gm, ' ');

