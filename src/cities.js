/**
 * Собирает заголовок, описание и H1 для страницы «услуга + город».
 *
 * Длину проверять не нужно вручную: сборка сама не пропустит слишком
 * длинный заголовок — см. проверку в build.js.
 */
function metaFor(cityKey, serviceKey, priceFrom) {
  const c = CITIES[cityKey];
  const s = SERVICES[serviceKey];
  if (!c || !s) throw new Error(`Нет такого города или услуги: ${cityKey} / ${serviceKey}`);

  /* Заголовок собираем «с запасом» и укорачиваем, пока не влезет в 65
     символов. Иначе длинные названия — «Telegram-бот в Минеральных Водах» —
     вылезают за границу, и выдача обрезает их посреди слова.

     Порядок отбрасывания не случаен: первой уходит цена (она есть на самой
     странице), потом уточнение услуги. Связка «услуга + город» остаётся
     всегда — ради неё заголовок и существует. */
  const LIMIT = 65;
  const base = `${s.name} в ${c.prep}`;
  const price = priceFrom ? ` ${priceFrom}` : '';

  const variants = [
    `${base} — ${s.short}${price}`,
    `${base} — ${s.short}`,
    `${base}${price}`,
    base,
  ];
  const title = variants.find((v) => v.length <= LIMIT) || base;

  return {
    title,
    h1: `${s.name} ${s.offer} в ${c.prep}`,
    description: `Настроим ${s.acc} в ${c.prep} ${s.offer}. Подходит малому бизнесу и услугам. ${s.trust}.`,
  };
}

