/**
 * Отзывы с Яндекс Карт — один источник правды для блока на страницах.
 *
 * ПОЧЕМУ НЕ СВОЙ СПИСОК ОТЗЫВОВ. Свой список — это слова студии о самой
 * себе: написать в нём можно что угодно, и цена такому ноль. Ещё хуже
 * разметка: подставлять чужие отзывы с Карт как свои aggregateRating
 * запрещено и в Яндексе, и в Google — за это понижают и карточку, и сайт.
 * Поэтому на странице стоит только то, что рисует сам Яндекс, а читать
 * и писать отзывы человек уходит в карточку.
 *
 * ПОЧЕМУ БЕЙДЖ, А НЕ РАМКА С ОТЗЫВАМИ. Рамка отзывов
 * yandex.ru/maps-reviews-widget/?id=... на 22.08.2026 отвечает 404 — и по
 * этой карточке, и по карточке «Граната» с живого сервера в России. То
 * есть виджет отзывов Яндекс сейчас не отдаёт вообще никому, дело не
 * в нашем сервере. А официальный бейдж рейтинга отвечает 200 и вставку
 * к себе не запрещает: в его заголовках нет ни X-Frame-Options,
 * ни frame-ancestors в CSP. Проверить обе ссылки: npm run otzyvy.
 *
 * КОГДА ЯНДЕКС ВЕРНЁТ РАМКУ — поменять RAMKA на true и пересобрать сайт
 * (npm run build). Разметка рамки уже лежит в src/partials/otzyvy.html,
 * переделывать блок не придётся.
 */

/* Номер карточки организации в Яндекс Картах. Тот же номер стоит
   в MAPS.orgUrl в src/pages.js — это ссылка «Открыть в Картах»
   на странице контактов. */
const ORG = '172151749064';

/* Показывать рамку с отзывами вместо бейджа. Сейчас false: Яндекс
   отдаёт по ней 404, и на странице получилась бы белая дыра в 560
   пикселей под заголовком. Пустая рамка выглядит поломкой сайта,
   а кнопка на карточку — нет. */
const RAMKA = false;

/* Показывать бейдж рейтинга. Выключатель нужен, потому что бейдж
   честно рисует то, что есть на карточке: пока оценок нет, на нём
   пять СЕРЫХ звёзд, и посетитель читает это как «ноль из пяти».
   До первых отзывов честнее оставить одни кнопки.

   ВЫКЛЮЧЕН 22.08.2026. Проверено раскодированием самой картинки бейджа:
   у карточки 172151749064 пять звёзд цвета #CCCCCC и ни одной цифры
   оценки — отзывов нет. Для сравнения, у карточки «Граната» в том же
   бейдже пять звёзд #FFCC00 и текст «4,3».

   Появятся первые отзывы — вернуть true и пересобрать. */
const BEJDZH = false;

/** Все адреса блока по номеру карточки. Собираем сами, чужой код
 *  в страницу не вставляем: вместе с ним приезжают чужие размеры,
 *  от которых вёрстка разъезжается на телефоне. */
function ssylki() {
  return {
    /* type=rating — тот же адрес, что даёт кабинет Яндекс Бизнеса
       в готовом коде бейджа. */
    bejdzh: `https://yandex.ru/sprav/widget/rating-badge/${ORG}?type=rating`,
    ramka: `https://yandex.ru/maps-reviews-widget/?id=${ORG}`,
    chitat: `https://yandex.ru/maps/org/${ORG}/reviews/`,
    napisat: `https://yandex.ru/maps/org/${ORG}/reviews/?add-review=true`,
  };
}

module.exports = { ORG, RAMKA, BEJDZH, ssylki };

/* ── Самопроверка: node src/otzyvy.js ────────────────────────────
   Ходит в Яндекс и говорит, что он сейчас отдаёт. Нужна затем, чтобы
   ответ на вопрос «а рамку уже можно включать?» занимал десять секунд,
   а не полдня в браузере. В сборке НЕ участвует: сборка не должна
   зависеть от того, доступен ли Яндекс с этой машины. */
if (require.main === module) {
  const https = require('https');
  const a = ssylki();

  const sprosit = (url) => new Promise((resolve) => {
    https.get(url, { headers: { 'User-Agent': 'Mozilla/5.0 (vibe-digital999.ru)' } }, (res) => {
      res.resume();
      const csp = res.headers['content-security-policy'] || '';
      resolve({
        kod: res.statusCode,
        xfo: res.headers['x-frame-options'] || '',
        predki: (csp.match(/frame-ancestors([^;]*)/i) || [])[1] || '',
      });
    }).on('error', (e) => resolve({ oshibka: e.message }));
  });

  (async () => {
    for (const [imya, url] of [['бейдж рейтинга', a.bejdzh], ['рамка отзывов', a.ramka]]) {
      const r = await sprosit(url);
      if (r.oshibka) { console.log(`${imya}: не спросить — ${r.oshibka}`); continue; }
      const zapret = r.xfo || r.predki
        ? `вставку запрещает (${r.xfo || 'frame-ancestors' + r.predki})`
        : 'вставку не запрещает';
      console.log(`${imya}: ответ ${r.kod}, ${zapret}\n  ${url}`);
    }
    console.log('\nРамку можно включать, когда у неё ответ 200 и вставка не запрещена:');
    console.log('  RAMKA = true в src/otzyvy.js, затем npm run build');
  })();
}
