require('dotenv').config();

/* IPv4 первым — иначе Telegram на Amvera висит до таймаута.
 *
 * DNS отдаёт для api.telegram.org и IPv4, и IPv6. IPv6 на Amvera не
 * работает: если Node выберет его, соединение не оборвётся с ошибкой,
 * а будет висеть, и выглядит это как «Telegram не отвечает». В соседнем
 * проекте это стоило двух падений бота за один день, второе — насмерть.
 *
 * Строка ставится ПЕРВОЙ, до любых сетевых вызовов: порядок адресов
 * выбирается при первом обращении, и потом менять его поздно.
 *
 * Важна точность: ipv4first ставит IPv4 первым, а не выкидывает IPv6.
 * Обычному клиенту этого хватает — он берёт первый адрес. Если зависания
 * останутся, IPv6 придётся отфильтровать явно, подменив dns.lookup. */
require('node:dns').setDefaultResultOrder('ipv4first');

const path = require('path');
const express = require('express');
const compression = require('compression');
const { handleLead, handleLeadsExport, resetLeadsIfAsked } = require('./api/lead');
const { handleBrief } = require('./api/brief');
const { handleGeo } = require('./api/geo');
const { startVkBot } = require('./api/vk-bot');
const { startTgBot } = require('./api/tg-bot');
const { startAutopost } = require('./api/autopost');
const { startBoli } = require('./api/boli');
const { startRedaktor } = require('./api/redaktor');
const { handlePlanPage, handlePlanCancel } = require('./api/plan-page');

const app = express();

/* За обратным прокси Amvera настоящий адрес посетителя приходит в заголовке,
   а не в сетевом соединении: в соединении сидит адрес самого прокси, всегда
   внутренний. Без этой строки req.ip возвращает его, и определение региона
   по IP отвечает «локальный адрес» каждому живому человеку.

   Значение true, а не число: сколько прокси стоит перед приложением, знает
   Amvera, а не мы, и их число может измениться при переезде на другой тариф.
   Заголовку доверяем потому, что снаружи до приложения не достучаться —
   весь трафик идёт через прокси, и подделать заголовок в обход него нельзя. */
app.set('trust proxy', true);
const PORT = process.env.PORT || 3000;

/* Сжатие. Страница у нас одна и очень насыщенная — 248 КБ текста,
   потому что весь HTML, CSS и скрипты лежат в одном файле. В сжатом
   виде это 63 КБ: вчетверо меньше, и разница целиком приходится
   на первый экран, до которого посетитель ждёт.
   Особенно заметно на мобильном интернете, а к нам приходят с телефонов.

   Ставится первой строкой: middleware работает на ответ, и всё, что
   зарегистрировано ниже, — статика, страницы, ошибки — пройдёт через
   неё. Картинки и шрифты compression пропускает сам: woff2, png и jpg
   уже сжаты, второй проход только тратит процессор.

   ВАЖНО: не сжимаем поток чата. Он отдаётся через text/event-stream
   по кусочку, а сжатие копит буфер перед отправкой — ответ ассистента
   приходил бы одним куском в конце, и вся идея живой печати пропадает. */
app.use(compression({
  filter(req, res) {
    if (res.getHeader('Content-Type')?.toString().includes('text/event-stream')) return false;
    return compression.filter(req, res);
  },
}));

app.use(express.json({ limit: '32kb' }));

/* ── Защита от спама ─────────────────────────────────────────────
   Считали по IP-адресу — и это тихо ломало приём заявок.

   За прокси Amvera адрес у всех посетителей ОДИН И ТОТ ЖЕ: прокси
   подставляет свой внутренний 10.x.x.x вместо адреса человека (см.
   api/geo.js, там та же причина). Значит лимит «5 заявок за 10 минут»
   действовал не на человека, а на весь сайт разом: шестой клиент за
   десять минут получал «слишком много заявок» и уходил. Заметить это
   было невозможно — в журнале ошибки нет, заявка просто не приходит.

   Теперь считаем по КОНТАКТУ. Он и есть то, что нужно ограничивать:
   спамер шлёт с одного адреса или ника, а десять разных клиентов
   в одну минуту — это удачный день, а не атака.

   Общий потолок оставлен, но поднят до уровня, на котором его задевает
   только поток от робота: пятнадцать заявок в минуту живые люди с сайта
   такого размера не дают. Он нужен на случай, если контакт в каждой
   заявке будет новым. */
const WINDOW_MS = 10 * 60 * 1000;
const MAX_PER_CONTACT = 3;        // один и тот же телефон или ник
const MAX_TOTAL = 150;            // весь сайт за то же окно — только против робота

const byContact = new Map();
let total = { start: 0, count: 0 };

/* Один и тот же телефон в разных записях выглядит по-разному:
   «+7 999 244-99-99», «89992449999», «8 (999) 244 99 99». Оставляем
   только цифры, иначе три записи одного номера считаются за три разных
   контакта и лимит не срабатывает вовсе. */
function contactKey(req) {
  const raw = String(req.body?.contact ?? '').trim().toLowerCase();
  if (!raw) return '';
  const digits = raw.replace(/\D/g, '');
  return digits.length >= 10 ? digits.slice(-10) : raw;
}

function rateLimit(req, res, next) {
  const now = Date.now();
  const tooMany = () => res.status(429).json({
    ok: false,
    error: 'Слишком много заявок подряд. Подождите десять минут или позвоните по +7 999 244 99 99.',
  });

  if (now - total.start > WINDOW_MS) total = { start: now, count: 0 };
  if (total.count >= MAX_TOTAL) return tooMany();
  total.count += 1;

  /* Контакта нет — заявку всё равно пропускаем: её отклонит проверка
     в api/lead.js с понятным человеку сообщением, а не безликим
     «слишком много заявок». */
  const key = contactKey(req);
  if (!key) return next();

  const record = byContact.get(key);
  if (!record || now - record.start > WINDOW_MS) {
    byContact.set(key, { start: now, count: 1 });
    return next();
  }

  if (record.count >= MAX_PER_CONTACT) return tooMany();

  record.count += 1;
  return next();
}

/* Чистим старые записи раз в час, чтобы память не росла. */
setInterval(() => {
  const now = Date.now();
  for (const [key, record] of byContact) {
    if (now - record.start > WINDOW_MS) byContact.delete(key);
  }
}, 60 * 60 * 1000).unref();

app.post('/api/lead', rateLimit, handleLead);

/* ИИ-брифер чата. Свой лимитер внутри: у диалога другой ритм, чем у заявки —
   пять сообщений за десять минут здесь мало, разговор оборвётся на середине. */
app.post('/api/brief', handleBrief);

/* Регион посетителя по IP — подсказка для полоски «похоже, вы из…».
   Подробности и предупреждения — в api/geo.js. Здесь важно одно: этот
   адрес ничего не решает за человека и не участвует в отдаче страниц.
   Робот его не вызывает — он не выполняет скрипты, — и /api/ закрыт
   в robots.txt. Любой адрес сайта отдаётся всем одинаково. */
app.get('/api/geo', handleGeo);

app.get('/health', (req, res) => res.json({ ok: true }));

/* Выгрузка сохранённых заявок. Закрыта ключом из переменной LEADS_KEY,
   без неё адрес отвечает 404 — внутри персональные данные посетителей. */
app.get('/api/leads', handleLeadsExport);

/* Короткие адреса для сторис.

   ЗАЧЕМ. В историях WhatsApp, Telegram и ВК ссылку нельзя нажать — адрес
   нарисован на картинке, и человек набирает его руками. Метку в такой адрес
   не впишешь: `?utm_source=whatsapp&utm_medium=stories` никто не наберёт.
   Мессенджеры при этом не сообщают сайту, откуда пришёл посетитель, поэтому
   Метрика видит визит без источника и относит его к прямым заходам. Все три
   канала сливаются в одну строку, и понять, какой из них работает, нельзя.

   КАК РЕШАЕМ. На картинке пишем vibe-digital999.ru/wa — два лишних символа,
   их наберут. Сервер отвечает переадресацией на главную с метками, и в
   Метрике (Отчёты → Источники → Метки UTM) каждый канал виден отдельно.

   Переадресация временная, 302: если завтра поменяем метки, браузер не будет
   держать у себя старый адрес. 301 закэшируется навсегда, и у тех, кто уже
   заходил, метки останутся прежними.

   Регистрируем ДО express.static: у статики включено extensions: ['html'],
   и без этого запрос /wa ушёл бы искать файл public/wa.html.

   utm_medium=stories отделяет истории от кликабельных ссылок в постах — там
   ставим ту же метку с utm_medium=post. Подробнее: docs/11-STORIES-METKI.md */
const STORY_SOURCES = {
  wa: 'whatsapp',
  tg: 'telegram',
  vk: 'vk',
};

/* КОРОТКИЙ АДРЕС ДЛЯ ТЕЛЕФОННОГО РАЗГОВОРА: vibe-digital999.ru/z
   Заведён 21.08.2026. Задача владелицы дословно: «Мне позвонили, а я
   прошу: перейдите, пожалуйста, на сайт и заполните заявку. Я не знаю,
   как это сделать».

   Проблема была в адресе. Реклама в Яндекс Бизнесе ведёт в карточку,
   а не на сайт; отдельную рекламу на сайт покупать не на что. Значит
   единственный бесплатный мост — сам разговор. Но продиктовать голосом
   «вайб дефис диджитал девятьсот девяносто девять точка ру, там форма
   внизу» невозможно: человек записывает с ошибкой и не доходит.

   Одна буква после адреса решает это: «наш сайт, слэш, зэ». Открывается
   сразу форма, а не главная, — листать и искать не нужно.

   Метка utm_source=zvonok отделяет этих людей в Метрике от всех
   остальных. Через неделю станет видно, сколько заявок приносит
   телефонный разговор, — а значит, стоит ли просить об этом каждого
   звонящего. */
app.get('/z', (req, res) => {
  res.redirect(302, '/?utm_source=zvonok&utm_medium=phone#order-section');
});

for (const [shortPath, source] of Object.entries(STORY_SOURCES)) {
  app.get(`/${shortPath}`, (req, res) => {
    res.redirect(302, `/?utm_source=${source}&utm_medium=stories`);
  });
}

/* План постов: что выйдет и когда, с возможностью снять лишнее.
   Закрыто ключом PLAN_KEY, без него оба адреса отвечают 404.
   Регистрируется ДО express.static — иначе /plan ушёл бы искать
   файл public/plan.html из-за extensions: ['html']. */
app.get('/plan', handlePlanPage);
app.post('/api/plan/cancel', handlePlanCancel);

/* Картинки и шрифты кэшируем надолго, а HTML — никогда:
   иначе после обновления сайта посетители ещё час видят старую страницу. */
app.use(express.static(path.join(__dirname, 'public'), {
  extensions: ['html'],
  maxAge: '7d',
  setHeaders(res, filePath) {
    if (filePath.endsWith('.html') || filePath.endsWith('.xml') || filePath.endsWith('.txt')) {
      res.setHeader('Cache-Control', 'no-cache');
    }
  },
}));

/* Несуществующий адрес.

   Раньше здесь отдавалась главная страница с кодом 404. Пока страница была
   одна, разницы не было. Теперь адресов много, ошибиться в них легко — и
   человек, набравший /uslugi/telegram-bota, видел бы главную и решил, что
   раздел просто исчез. Страница 404 говорит прямо: адреса нет, вот разделы.

   Код именно 404, а не 200 с текстом «не найдено»: по коду робот понимает,
   что страницу не надо держать в индексе. Страница 404 закрыта от индексации
   мета-тегом и в sitemap.xml не входит.

   Запасной путь на случай, если файла нет (сборка не отработала): отдаём
   главную. Пустой ответ хуже неточного. */
app.use((req, res) => {
  res.status(404).sendFile(path.join(__dirname, 'public', '404.html'), (err) => {
    if (err) res.status(404).sendFile(path.join(__dirname, 'public', 'index.html'));
  });
});

app.listen(PORT, () => {
  console.log(`Сайт запущен: http://localhost:${PORT}`);

  /* До ботов: если попросили сбросить нумерацию после проверок, сделать
     это раньше, чем придёт первая заявка. Без переменной RESET_LEADS
     вызов ничего не делает и молчит. */
  resetLeadsIfAsked();

  /* Боты живут в этом же процессе: отдельное приложение на Amvera —
     это второй счёт и второй деплой ради одного долгого запроса.

     Каждый запускается независимо и ничего не пробрасывает наверх.
     Это не перестраховка: в соседнем проекте ошибка запуска Telegram
     дошла до верха и остановила процесс, унеся с собой бот ВКонтакте —
     ровно тот канал, который и заведён на случай смерти Telegram.
     Здесь в том же процессе живёт ещё и сайт, так что цена такой
     ошибки — весь сайт. */
  startVkBot();
  startTgBot();
  startAutopost();
  startBoli();

  /* Редакция последней: она читает боли, собранные разбором, и дописывает
     план, из которого публикует расписание. Порядок запуска на это не
     влияет — каждый работает по своему таймеру, — но читается так же,
     как идёт работа: разбор → редакция → публикация. */
  startRedaktor();
});
