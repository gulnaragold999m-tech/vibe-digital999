/**
 * Какие каналы связи включены.
 *
 * Модуль без зависимостей, чтобы его мог спросить кто угодно —
 * и приём заявок, и бот, и сервер при запуске.
 *
 * ── TELEGRAM ВЫКЛЮЧЕН 14.08.2026 ──────────────────────────────────
 *
 * Решение владелицы, её словами: «остановить бота, мы пока не работаем
 * с площадкой телеграм». Причина — у неё нет соединения с Telegram,
 * он попросту не открывается.
 *
 * Почему это правильно, а не просто исполнение просьбы:
 *
 * 1. Заявка считается доставленной, если её принял ХОТЯ БЫ ОДИН канал.
 *    Telegram с нашего сервера работает и тогда, когда не открывается
 *    у человека. То есть заявка уходила туда, помечалась доставленной —
 *    и оставалась непрочитанной. В журнале при этом всё выглядело
 *    исправным.
 * 2. Мы предлагали клиентам писать в Telegram — в подвале, в контактах
 *    и устами бота. Люди писали в канал, который никто не читает.
 * 3. api.telegram.org — заграница, и туда уходили имя и телефон целиком.
 *    Маскировкой это не закрыть: в том и смысл канала, что владелица
 *    должна видеть настоящий номер. Выключив канал, мы заодно закрыли
 *    трансграничную передачу — см. docs/21, раздел 4.
 *
 * ВЕРНУТЬ ОБРАТНО: переменная окружения TELEGRAM_KANAL=on в Amvera
 * и перезапуск приложения. Код никто не трогает. Но перед этим —
 * решить вопрос с политикой конфиденциальности (docs/21, раздел 5).
 */

/** Включён ли Telegram как канал: доставка заявок и бот для клиентов. */
function telegramVklyuchen() {
  return String(process.env.TELEGRAM_KANAL || '').trim().toLowerCase() === 'on';
}

module.exports = { telegramVklyuchen };
