/**
 * Совещание редакции: фактчекер и критик читают готовый текст.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ МОДУЛЕМ. `redaktor.js` работает на живом сервере
 * и раз в полминуты решает, публиковать ли пост. Ломать его правкой
 * в семьсот строк — значит рисковать всей лентой. Совещание живёт
 * рядом, и `redaktor.js` вызывает его одной строкой.
 *
 * ЧТО ЭТО ДАЁТ СВЕРХ ПРИЁМКИ. Приёмка скриптовая и грубая: цены
 * не из прайса, штампы, гарантии, повторы, markdown, чужой канал.
 * Она НЕ ловит два класса ошибок, которые стоили нам дороже всего:
 *
 *   · обещание услуги, которой у студии нет — «ажурная резка»,
 *     «разработка логотипа», «картон 300». Технически цена верная,
 *     стиль хороший, приёмка молчит, а написана неправда;
 *   · то, что формально верно, но бьёт по репутации — разбор
 *     собственного провала, снисходительность к читателю, пустой конец.
 *
 * ПРАВИЛА СОВЕЩАНИЯ, и они важнее кода:
 *   1. Круг ровно ОДИН. Второй круг — это переписка ролей между собой:
 *      токены жжёт, качество почти не растёт, пост не выходит.
 *   2. Роли НЕ переписывают текст. Находят — правит копирайтер.
 *      Иначе никто ни за что не отвечает.
 *   3. Совещание НЕ отменяет приёмку. Она идёт после и она скриптовая:
 *      ИИ устаёт и уговаривается, код — нет.
 *   4. Молчание роли запрещено. Нечего сказать — так и пишет.
 *      Пустой ответ хуже отсутствия роли: непонятно, работала ли она.
 *
 * ГДЕ ОПИСАНЫ САМИ РОЛИ. В папке `roli/`, отдельными файлами. Это
 * источник правды: те же файлы читают агенты в чате. Правило то же,
 * что с ценами, — роль описана в ОДНОМ месте, иначе разъедется.
 */
const fs = require('fs');
const path = require('path');

const PRICES = require('../src/prices');

/* Ссылка на модель берётся В МОМЕНТ ВЫЗОВА, а не при загрузке модуля.
   Причина не в красоте: с деструктуризацией `const { askOnce } = ...`
   модуль нельзя проверить подставной моделью — ссылка уже захвачена,
   и проверка молча уходит в настоящую сеть. Так и вышло на первом
   же прогоне: тест «роли нашли проблемы» показал «чисто», потому что
   настоящая модель упала без ключа, а падение гасится как «замечаний
   нет». Проверка, которую нельзя обмануть подставной моделью, — это
   проверка, которая ничего не проверяет. */
function model() {
  return require('./brief').askOnce;
}

const ROLI = path.join(__dirname, '..', 'roli');

/** Описание роли из файла. Нет файла — роль молча выключается:
 *  совещание не должно ронять публикацию из-за пропавшего текста. */
function rol(imya) {
  try {
    return fs.readFileSync(path.join(ROLI, imya + '.md'), 'utf8');
  } catch {
    return '';
  }
}

/** Что студии разрешено обещать: услуги и суммы из прайса. */
function chtoUmeem() {
  const uslugi = PRICES.USLUGI.map((u) => `${u.nazvanie} — ${u.cena} ₽`);
  const pakety = (PRICES.PAKETY || []).map((p) => `${p.nazvanie} — ${PRICES.cenaPaketa(p)} ₽`);
  return [...uslugi, ...pakety];
}

/** Чего у студии нет. Пока список живёт в прайсе типографии, здесь
 *  общий свод: то, чего не умеет ни одно из двух направлений. */
const CHEGO_NET = [
  'офсетная печать — её нет, тиражи печатаем на своей технике и дороже',
  'ажурная, контурная и фигурная резка — нужен режущий плоттер, у нас печатающий',
  'конгрев, слепое тиснение, УФ-лак',
  'разработка логотипа и фирменного стиля',
  'съёмка на документы — печатаем готовый файл, но не снимаем',
  'квартальные и перекидные календари на пружине',
  'бумага плотнее 260 г/м² — принтер не берёт',
  'круглосуточная работа',
  'гарантия результата и позиций в поиске',
];

/** Один участник совещания. Возвращает текст замечаний. */
async function uchastnik(imya, tekst, tz, dopolnitelno) {
  const opisanie = rol(imya);
  if (!opisanie) return '';

  const system = [
    opisanie,
    '',
    'Отвечай коротко и по делу. Список замечаний или прямая фраза,',
    'что замечаний нет. Не переписывай текст — это работа копирайтера.',
  ].join('\n');

  const vopros = [
    'ЗАДАНИЕ, ПО КОТОРОМУ ПИСАЛСЯ ПОСТ:',
    tz && tz.zadacha ? tz.zadacha : '(задание не передано)',
    '',
    ...(dopolnitelno || []),
    '',
    'ТЕКСТ ПОСТА:',
    String(tekst),
  ].join('\n');

  try {
    return String(await model()([{ role: 'user', content: vopros }], system)).trim();
  } catch (e) {
    // Роль упала — совещание продолжается без неё. Пост важнее совещания.
    return `(${imya}: не ответил — ${String(e.message).slice(0, 80)})`;
  }
}

/** Замечание считается пустым, если роль прямо сказала, что их нет. */
function pusto(otvet) {
  return !otvet || /^\(|расхожден(ий|ия) нет|замечан(ий|ия) нет|возражени(й|я) нет|нет замечаний|нет расхождений/i
    .test(otvet.trim().slice(0, 120));
}

/**
 * Провести совещание над готовым текстом.
 * Возвращает { zamechaniya: [...], chisto: true|false }.
 */
async function soveshchanie(tekst, tz) {
  const [fakt, krit] = await Promise.all([
    uchastnik('faktchek', tekst, tz, [
      'ЧТО СТУДИЯ УМЕЕТ И ПОЧЁМ (другого обещать нельзя):',
      ...chtoUmeem().map((s) => '  ' + s),
      '',
      'ЧЕГО У СТУДИИ НЕТ — упоминание как своей услуги это брак:',
      ...CHEGO_NET.map((s) => '  ' + s),
    ]),
    uchastnik('kritik', tekst, tz, []),
  ]);

  const zamechaniya = [];
  if (!pusto(fakt)) zamechaniya.push({ rol: 'фактчекер', tekst: fakt });
  if (!pusto(krit)) zamechaniya.push({ rol: 'критик', tekst: krit });

  return { zamechaniya, chisto: zamechaniya.length === 0 };
}

module.exports = { soveshchanie, chtoUmeem, CHEGO_NET };
