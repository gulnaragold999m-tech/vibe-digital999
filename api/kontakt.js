/**
 * Контакт из текста посетителя: телефон, почта или ник.
 *
 * Отдельным модулем и БЕЗ ЗАВИСИМОСТЕЙ намеренно. Это место решает,
 * станет разговор заявкой или пропадёт, поэтому у него есть свои
 * проверки — `npm run test-kontakt`. Лежи оно внутри api/brief.js,
 * тест тянул бы за собой почту, ВК и ключ модели, и запустить его
 * на обычном компьютере было бы нечем.
 */

/* ── Контакт в тексте: телефон, ник или почта ─────────────────────
   Это место решает, станет разговор заявкой или пропадёт. Ошибка здесь
   не видна ниоткуда: бот отвечает как обычно, человек уверен, что оставил
   телефон, а владелице не приходит ничего и в журнале пусто.

   Две дыры, найдены 14.08.2026 проверкой на живых написаниях:

   1. Прежний шаблон допускал ровно ОДИН разделитель между группами цифр.
      Запись «+7 (999) 244-99-99», где после кода идут пробел И скобка,
      он не ловил — а это самый частый способ написать номер. Теперь
      считаем цифры, а не разделители.
   2. Почта опознавалась как ник: из mail@yandex.ru доставалось «@yandex»,
      и владелица получала контакт несуществующего аккаунта. Теперь почта
      проверяется раньше ника и годится как контакт сама по себе.

   Порядок проверки — от надёжного к запасному: телефон, почта, ник. ── */
const POCHTA_RE = /[\w.+-]+@[\w-]+\.[a-z]{2,}/i;

/* Кусок текста, похожий на номер: цифры с разделителями подряд. Буквы,
   запятая и знак рубля такой кусок обрывают — поэтому «бюджет 150 000 ₽»
   и «12 номеров» сюда не попадают. */
const TELEFON_RE = /\+?\d[\d\s()-]{8,18}\d/g;

/**
 * Телефон из текста, приведённый к виду +7XXXXXXXXXX.
 *
 * Единый вид нужен не для красоты: по контакту считается повтор
 * (см. notifyOwner). Человек, написавший номер сначала со скобками,
 * а потом без, иначе присылал бы владелице две одинаковые заявки.
 */
function findPhone(text) {
  for (const raw of text.match(TELEFON_RE) || []) {
    const digits = raw.replace(/\D/g, '');

    /* Первая группа цифр отличает телефон от диапазона цен. У номера она
       либо код страны в одиночку («8 999 244 99 99»), либо весь номер
       разом («89992449999»). У записи «80 000-250 000» первая группа —
       две цифры, и по одной этой примете она отсеивается, хотя всего
       цифр в ней тоже одиннадцать. */
    const pervaya = (raw.match(/\d+/) || [''])[0].length;
    const sKodom = raw.trimStart().startsWith('+') || pervaya === 1 || pervaya === 11;

    if (digits.length === 11 && /^[78]/.test(digits) && sKodom) return '+7' + digits.slice(1);
    /* Десять цифр без кода страны — только мобильный, он всегда с девятки. */
    if (digits.length === 10 && digits.startsWith('9')) return '+7' + digits;
  }
  return null;
}

/** Телефон, почта или ник — признак, что разговор дозрел до заявки. */
function findContact(text) {
  const phone = findPhone(text);
  if (phone) return phone;

  const mail = text.match(POCHTA_RE);
  if (mail) return mail[0].toLowerCase();

  /* Ник — только там, где перед собакой нет имени почтового ящика. */
  const nick = text.match(/(?:^|[^\w@.-])@([a-zA-Z][a-zA-Z0-9_]{3,31})\b/);
  return nick ? '@' + nick[1] : null;
}

module.exports = { findContact, findPhone };
