async function kopirajter(tz, zamechanie) {
  const system = tz.vk_group === 'granat' ? KOPIRAJTER_GRANAT : KOPIRAJTER_AGENTSTVO;

  const zadanie = [
    `Ниша: ${tz.nisha || 'предприниматели Кавминвод'}`,
    `Боль: ${tz.bol || tz.zadacha}`,
    `Задача: ${tz.zadacha}`,
    `Формат: ${tz.format || 'разбор'}`,
    `Действие в конце: ${tz.cta || 'написать в сообщения сообщества'}`,
    zamechanie ? `\nПрошлый вариант забракован: ${zamechanie}\nНапиши заново, без этой ошибки.` : '',
  ].filter(Boolean).join('\n');

  const otvet = String(await askOnce([{ role: 'user', content: zadanie }], system)).trim();
  const razobrano = parseJsonObject(otvet);

  /* Модель иногда отвечает просто текстом, забыв про JSON. Это не повод
     терять пост: берём весь ответ как текст, комментария тогда не будет.
     Обратный случай опаснее — пустой text при заполненном JSON: такой
     пост уйдёт в приёмку и честно забракуется как «слишком коротко». */
  if (razobrano && typeof razobrano.text === 'string' && razobrano.text.trim()) {
    return {
      text: razobrano.text.trim(),
      comment: typeof razobrano.comment === 'string' ? razobrano.comment.trim() : '',
    };
  }

  return { text: otvet, comment: '' };
}

