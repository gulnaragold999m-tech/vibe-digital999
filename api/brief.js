/* ── Лимит: защищает кошелёк от перебора запросов с одного адреса ── */
const hits = new Map();
const LIMIT = 40;
const WINDOW_MS = 10 * 60 * 1000;

function overLimit(ip) {
  const now = Date.now();
  const rec = hits.get(ip) || { n: 0, t: now };
  if (now - rec.t > WINDOW_MS) { rec.n = 0; rec.t = now; }
  rec.n += 1;
  hits.set(ip, rec);
  if (hits.size > 5000) hits.clear();   // грубая, но бесплатная сборка мусора
  return rec.n > LIMIT;
}

