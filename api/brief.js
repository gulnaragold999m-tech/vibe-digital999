const notified = new Set();

function escapeHtml(text) {
  return String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

/** Телефон или ник — признак, что разговор дозрел до заявки. */
function findContact(text) {
  const phone = text.match(/(?:\+7|8)[\s(-]?\d{3}[\s)-]?\d{3}[\s-]?\d{2}[\s-]?\d{2}/);
  if (phone) return phone[0];
  const nick = text.match(/@[a-zA-Z0-9_]{4,32}/);
  if (nick) return nick[0];
  return null;
}

/**
 * Шлёт бриф владельцу — в Telegram и ВКонтакте сразу.
 *
 * Два канала по той же причине, что и у заявок с формы (см. api/vk.js):
 * разговор с живым человеком, который уже назвал телефон, — самое дорогое,
 * что есть на сайте, и терять его из-за отказа одного мессенджера нельзя.
 */
async function notifyOwner(messages, contact, sessionKey) {
  if (notified.has(sessionKey)) return;    // один бриф на диалог, без спама
  notified.add(sessionKey);
  if (notified.size > 2000) notified.clear();

  const dialog = messages
    .map(m => (m.role === 'user' ? '👤 ' : '🤖 ') + m.content)
    .join('\n')
    .slice(0, 3000);

  const site = process.env.SITE_NAME || 'vibe-digital999.ru';

  const plainText = [
    '💬 ВАЙБКОДИНГ — бриф из чата',
    `🌐 ${site}`,
    '',
    `📱 Контакт: ${contact}`,
    '',
    'Диалог:',
    dialog,
  ].join('\n');

  const htmlText = [
    '💬 <b>ВАЙБКОДИНГ — бриф из чата</b>',
    `🌐 ${escapeHtml(site)}`,
    '',
    `📱 Контакт: ${escapeHtml(contact)}`,
    '',
    '<b>Диалог:</b>',
    escapeHtml(dialog),
  ].join('\n');

  const token = process.env.BOT_TOKEN;
  const chatId = process.env.CHAT_ID;

  const [tg, vk] = await Promise.all([
    (async () => {
      if (!token || !chatId) return { ok: false, error: 'BOT_TOKEN или CHAT_ID не заданы' };
      try {
        const res = await fetch(`${TELEGRAM_API}/bot${token}/sendMessage`, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ chat_id: chatId, text: htmlText, parse_mode: 'HTML' }),
        });
        const data = await res.json();
        return data.ok ? { ok: true } : { ok: false, error: `${data.error_code} ${data.description}` };
      } catch (err) {
        return { ok: false, error: err.message };
      }
    })(),
    vkConfigured() ? sendVkToOwner(plainText) : Promise.resolve({ ok: false, error: 'не подключён' }),
  ]);

  if (tg.ok || vk.ok) {
    console.log(`[brief] Бриф отправлен: ${contact}`,
      `| Telegram: ${tg.ok ? 'доставлено' : tg.error}`,
      `| ВК: ${vk.ok ? 'доставлено' : vk.error}`);
  } else {
    console.error(`[brief] ❌ Бриф НЕ доставлен ни одним каналом: ${contact}.`,
      `Telegram: ${tg.error} | ВК: ${vk.error}. Диалог:`, dialog.slice(0, 500));
  }
}

