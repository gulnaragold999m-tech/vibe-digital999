/* Пакеты и сопровождение — отдельной категорией. В карточке они полезнее
   отдельных услуг: у пакета цена конечная, а не «от», и человеку сразу
   видно, во что обойдётся запуск целиком. Состав и цена считаются
   из src/prices.js, руками здесь не записаны. */
function paketyKategoriya() {
  const pozicii = PRICES.PAKETY.map((p) => {
    const sostav = p.sostav
      .map((id) => PRICES.usluga(id).nazvanie.replace(/ \(.*\)$/, ''))
      .join(' + ');
    return {
      nazvanie: `Пакет ${p.nazvanie} — запуск под ключ`,
      cenaGotovaya: 'от ' + PRICES.rub(PRICES.cenaPaketa(p)),
      opisanie: `${sostav}. ${p.komu} Срок ${p.srok}. Сопровождение после сдачи — ${PRICES.rub(p.soprovozhdenie)} в месяц, ${p.chasy}. Обсудим, что подойдёт вам.`,
    };
  });

  pozicii.push({
    nazvanie: 'Сопровождение сайта по абонентской плате',
    cenaGotovaya: 'от ' + PRICES.rub(Math.min(...PRICES.PAKETY.map((p) => p.soprovozhdenie))),
    opisanie: 'Правки, обновления и присмотр за сайтом каждый месяц: от 1 до 3 часов работы в зависимости от пакета. Круглосуточного дежурства у нас нет, работаем в будни с 9:00 до 18:00. Спросите, что входит.',
  });

  return { nazvanie: 'Пакеты и сопровождение', pozicii };
}

/* ── Сборка ──────────────────────────────────────────────────── */

const LINIYA = '─'.repeat(66);

function sobrat() {
  const kategorii = [...KATEGORII, paketyKategoriya()];
  const bezCeny = [];
  const out = [];
  let vsego = 0;

  out.push('ПРАЙС ДЛЯ КАРТОЧКИ В ЯНДЕКС КАРТАХ');
  out.push('');
  out.push('Собран из src/prices.js — цены те же, что на сайте и у бота.');
  out.push('Руками здесь ничего не правьте: следующий запуск сотрёт.');
  out.push('Цену менять в src/prices.js, потом снова: npm run karty');
  out.push('');
  out.push('Куда заводить: Яндекс Бизнес → ваша организация → Товары');
  out.push('и услуги → добавить категорию → добавить позицию.');
  out.push('Три поля: название, цена, описание.');
  out.push('');
  out.push('Заводите ПО ОДНОЙ КАТЕГОРИИ за раз. Всё сразу не осилить,');
  out.push('а брошенный на середине прайс выглядит хуже короткого,');
  out.push('но законченного.');
  out.push('');

  kategorii.forEach((k, i) => {
    out.push(LINIYA);
    out.push(`КАТЕГОРИЯ ${i + 1}. ${k.nazvanie.toUpperCase()}`);
    out.push(LINIYA);
    out.push('');

    k.pozicii.forEach((p) => {
      if (!p.cena && !p.cenaGotovaya) {
        bezCeny.push(p);
        return;
      }
      vsego += 1;
      out.push(`${vsego}. ${p.nazvanie}`);
      out.push(`   Цена: ${p.cenaGotovaya || PRICES.cena(p.cena)}`);
      out.push(`   Описание: ${p.opisanie}`);
      out.push('');
    });
  });

  if (bezCeny.length) {
    out.push(LINIYA);
    out.push('ЦЕНУ ПРОСТАВИТЬ РУКАМИ — В ПРАЙСЕ СТУДИИ ЕЁ НЕТ');
    out.push(LINIYA);
    out.push('');
    out.push('Эти позиции я не выдумываю. Решите цену — скажите, впишу');
    out.push('в src/prices.js, и они встанут в список сами.');
    out.push('Позиция без цены выглядит слабее: человек уходит сравнивать');
    out.push('к тому, у кого цена написана.');
    out.push('');
    bezCeny.forEach((p, i) => {
      out.push(`${i + 1}. ${p.nazvanie}`);
      out.push(`   Цена: ____________`);
      out.push(`   Описание: ${p.opisanie}`);
      out.push('');
    });
  }

  out.push(LINIYA);
  out.push('ЧЕГО НЕ ДЕЛАТЬ');
  out.push(LINIYA);
  out.push('');
  out.push('Не ставить логотипы и надписи на фотографии — модерация');
  out.push('Яндекса снимает снимки с рекламными наложениями.');
  out.push('');
  out.push('Не дублировать названия. Разные слова об одном — нормально,');
  out.push('две позиции с ОДИНАКОВЫМ названием Яндекс склеит.');
  out.push('');
  out.push('Бот для WhatsApp в список намеренно не включён. Обещать');
  out.push('«официально и без риска блокировки» мы не можем: официальный');
  out.push('путь уводит имя и телефон клиента за границу, а обходные');
  out.push('пути WhatsApp наказывает блокировкой номера. Разобрано');
  out.push('в TASKS.md, запись от 11.08.2026.');
  out.push('');

  return { text: out.join('\n'), vsego, bezCeny: bezCeny.length };
}

const { text, vsego, bezCeny } = sobrat();
